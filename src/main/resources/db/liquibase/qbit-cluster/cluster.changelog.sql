-- changeset qbit-cluster:1
-- comment: One row per running (or recently running) node of the application: who it is, where it runs, its roles, its heartbeat and status, and any drain request.
CREATE TABLE IF NOT EXISTS cluster_node (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   node_id VARCHAR(250) NOT NULL,
   pod_name VARCHAR(250),
   k8s_node_name VARCHAR(250),
   zone VARCHAR(100),
   deployment VARCHAR(250),
   roles VARCHAR(100),
   version VARCHAR(100),
   started_at TIMESTAMP,
   heartbeat_at TIMESTAMP,
   status VARCHAR(20),
   worker_threads INTEGER,
   scheduler_active BOOLEAN,
   esb_triggers_active BOOLEAN,
   async_jobs_running INTEGER,
   heap_used_mb INTEGER,
   heap_max_mb INTEGER,
   drain_requested BOOLEAN DEFAULT FALSE,
   drain_requested_by VARCHAR(250),
   drain_reason VARCHAR(500),
   create_date TIMESTAMP,
   modify_date TIMESTAMP,
   CONSTRAINT pk_cluster_node PRIMARY KEY (id),
   CONSTRAINT uq_cluster_node_node_id UNIQUE (node_id)
);
-- rollback DROP TABLE IF EXISTS cluster_node;

-- changeset qbit-cluster:2
-- comment: The lost-node sweep and purge find nodes by status and heartbeat age.
CREATE INDEX IF NOT EXISTS ix_cluster_node_status_heartbeat ON cluster_node (status, heartbeat_at);
-- rollback DROP INDEX IF EXISTS ix_cluster_node_status_heartbeat;

-- changeset qbit-cluster:3
-- comment: Named leases for singletons that are not Quartz jobs (ClusterLeases). Every change is a compare-and-set on version.
CREATE TABLE IF NOT EXISTS cluster_lease (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   name VARCHAR(100) NOT NULL,
   holder_node_id VARCHAR(250),
   expires_at TIMESTAMP,
   version INTEGER NOT NULL DEFAULT 0,
   acquired_at TIMESTAMP,
   create_date TIMESTAMP,
   modify_date TIMESTAMP,
   CONSTRAINT pk_cluster_lease PRIMARY KEY (id),
   CONSTRAINT uq_cluster_lease_name UNIQUE (name)
);
-- rollback DROP TABLE IF EXISTS cluster_lease;

-- changeset qbit-cluster:4
-- comment: The cluster's settings (heartbeat_seconds, lost_after_seconds, retain_stopped_days, alert_on_lost), seeded by cluster-defaults.changelog.sql.
CREATE TABLE IF NOT EXISTS cluster_setting (
   id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
   setting_key VARCHAR(100) NOT NULL,
   setting_value VARCHAR(250) NOT NULL,
   description VARCHAR(500),
   create_date TIMESTAMP,
   modify_date TIMESTAMP,
   CONSTRAINT pk_cluster_setting PRIMARY KEY (id),
   CONSTRAINT uq_cluster_setting_setting_key UNIQUE (setting_key)
);
-- rollback DROP TABLE IF EXISTS cluster_setting;
